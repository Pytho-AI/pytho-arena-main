#!/usr/bin/env bash
# Import the versioned contract bundle from coa-engine and regenerate both
# Arena clients:
#   - contracts-import/            pinned copy of protos + dist hashes + fixtures
#   - src/pytho/sim/v1/            generated Python bindings + gRPC stubs
#   - server frontend src/contracts/pytho/sim/v1/  generated TypeScript codecs
# COA is located through COA_ENGINE_DIR (default: ../coa-engine).
# Usage: scripts/sync-coa-contracts.sh [--check]
#   --check: verify the imported copy and generated clients match a fresh
#            regeneration (and COA's current bundle) without writing.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COA="${COA_ENGINE_DIR:-${REPO_ROOT}/../coa-engine}"
COA="$(cd "${COA}" && pwd)"
# Resolve rather than hardcode: CI has no .venv, and an unresolvable path exits
# 127, which the freshness gate would misreport as stale generated clients.
if [[ -n "${PYTHON:-}" ]]; then
  :
elif [[ -x "${REPO_ROOT}/.venv/bin/python" ]]; then
  PYTHON="${REPO_ROOT}/.venv/bin/python"
else
  PYTHON="$(command -v python3 || command -v python)"
fi
[[ -n "${PYTHON}" ]] || { echo "no python interpreter found" >&2; exit 2; }
FRONTEND="${REPO_ROOT}/src/pytho_arena/server/frontend-src"
IMPORT_DIR="${REPO_ROOT}/contracts-import"

[[ -d "${COA}/contracts/pytho/sim/v1" ]] || { echo "COA contracts not found at ${COA}" >&2; exit 2; }

# Verify COA's bundle integrity before importing anything.
(cd "${COA}/contracts" && shasum -a 256 -c dist/SHA256SUMS --quiet --ignore-missing) \
  || { echo "COA contract bundle fails its own SHA256SUMS" >&2; exit 2; }

import_into() {
  local dst="$1"
  mkdir -p "${dst}/pytho/sim/v1" "${dst}/dist" "${dst}/fixtures"
  cp "${COA}/contracts/pytho/sim/v1/"*.proto "${dst}/pytho/sim/v1/"
  cp "${COA}/contracts/dist/SHA256SUMS" "${COA}/contracts/dist/MANIFEST" \
     "${COA}/contracts/dist/descriptor_set.binpb" "${dst}/dist/"
  cp "${COA}/contracts/fixtures/"*.binpb "${COA}/contracts/fixtures/logical_hash.json" "${dst}/fixtures/"
}

gen_python() {
  local src="$1" out="$2"
  mkdir -p "${out}"
  "${PYTHON}" -m grpc_tools.protoc -I"${src}" \
    --python_out="${out}" --grpc_python_out="${out}" \
    "${src}"/pytho/sim/v1/*.proto
  for d in "${out}/pytho" "${out}/pytho/sim" "${out}/pytho/sim/v1"; do
    printf '# @generated by scripts/sync-coa-contracts.sh — do not edit.\n' > "${d}/__init__.py"
  done
}

gen_ts() {
  local src="$1" out="$2"
  mkdir -p "${out}"
  "${PYTHON}" -m grpc_tools.protoc -I"${src}" \
    --plugin=protoc-gen-es="${FRONTEND}/node_modules/.bin/protoc-gen-es" \
    --es_out="${out}" --es_opt=target=ts \
    "${src}"/pytho/sim/v1/*.proto
}

if [[ "${1:-}" == "--check" ]]; then
  TMP="$(mktemp -d)"
  trap 'rm -rf "${TMP}"' EXIT
  import_into "${TMP}/import"
  gen_python "${TMP}/import" "${TMP}/py"
  gen_ts "${TMP}/import" "${TMP}/ts"
  status=0
  diff -r "${TMP}/import" "${IMPORT_DIR}" || status=1
  diff -r -x '__pycache__' "${TMP}/py/pytho" "${REPO_ROOT}/src/pytho" || status=1
  diff -r "${TMP}/ts/pytho" "${FRONTEND}/src/contracts/pytho" || status=1
  if [[ ${status} -ne 0 ]]; then
    echo "STALE CONTRACT CLIENTS — run scripts/sync-coa-contracts.sh" >&2
    exit 1
  fi
  echo "arena contract clients fresh"
else
  import_into "${IMPORT_DIR}"
  gen_python "${IMPORT_DIR}" "${REPO_ROOT}/src"
  gen_ts "${IMPORT_DIR}" "${FRONTEND}/src/contracts"
  echo "imported bundle + regenerated Python and TypeScript clients"
fi
